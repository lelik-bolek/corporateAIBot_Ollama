from typing import List, Dict, Any

# 1. Системная инструкция с жесткими правилами Chain-of-Thought (CoT)
SYSTEM_PROMPT = (
    "Ты — интеллектуальный корпоративный ассистент вселенной Star Wars.\n"
    "Твоя задача — отвечать на вопросы сотрудников строго на основе предоставленного контекста.\n\n"
    "ПРАВИЛА И СТРУКТУРА ОТВЕТА:\n"
    "1. Применяй Chain-of-Thought: сначала напиши блок «Рассуждение:» с нумерованными шагами (1, 2, 3), "
    "в которых сопоставь факты из контекста. Затем напиши блок «Ответ:» с итоговым выводом.\n"
    "2. Опирайся ТОЛЬКО на факты из блока <КОНТЕКСТ>. Не используй внешние знания и не придумывай факты.\n"
    "3. Если в контексте нет прямого ответа на вопрос, в блоке «Ответ:» напиши строго: "
    "«Я не знаю. В корпоративной базе знаний нет информации по данному вопросу.»\n"
    "4. Не выдумывай примеры дальше и завершай генерацию сразу после итогового ответа."
)

# 2. Few-Shot примеры из предметной области (на базе подмененных сущностей)
FEW_SHOT_EXAMPLES = (
    "--- ПРИМЕРЫ ВЫПОЛНЕНИЯ ---\n\n"
    "Пример 1:\n"
    "<КОНТЕКСТ>\n"
    "[1] mustafar.txt: Чу-Гон Дар создал артефакт — куб Чу-Гон Дара, "
    "способный трансформировать материю на планете Пирос с помощью Синт-Эфира.\n"
    "</КОНТЕКСТ>\n"
    "Вопрос: Какой уникальный объект создал Чу-Гон Дар?\n"
    "Рассуждение:\n"
    "1. В вопросе запрашивается уникальный объект, созданный Чу-Гон Даром.\n"
    "2. В документе mustafar.txt указано, что он создал артефакт под названием «куб Чу-Гон Дара».\n"
    "3. Объект предназначался для трансформации материи на планете Пирос.\n"
    "Ответ: Чу-Гон Дар создал уникальный артефакт — куб Чу-Гон Дара.\n\n"
    "Пример 2:\n"
    "<КОНТЕКСТ>\n"
    "[1] darth_vader.txt: Ксарн Велгор носил тяжелую кибернетическую броню после дуэли на планете Пирос.\n"
    "</КОНТЕКСТ>\n"
    "Вопрос: Какая максимальная скорость у звездолета Сокол Эфира?\n"
    "Рассуждение:\n"
    "1. Запрос касается технических характеристик звездолета «Сокол Эфира».\n"
    "2. В контексте содержится информация только о броне Ксарна Велгора.\n"
    "3. Сведений о звездолете «Сокол Эфира» в базе знаний нет.\n"
    "Ответ: Я не знаю. В корпоративной базе знаний нет информации по данному вопросу.\n"
    "--- КОНЕЦ ПРИМЕРОВ ---\n\n"
)


def format_rag_messages(query: str, context_chunks: List[Dict[str, Any]]) -> List[Dict[str, str]]:
    """
    Формирует список сообщений (System + User Context/Few-Shot/Query) для LLM.
    """
    context_text = "<КОНТЕКСТ>\n"
    for i, chunk in enumerate(context_chunks, start=1):
        clean_text = chunk["text"].replace("\n", " ")
        context_text += f"[{i}] {chunk['source_file']}: {clean_text}\n"
    context_text += "</КОНТЕКСТ>\n"

    user_content = (
        f"{FEW_SHOT_EXAMPLES}"
        f"Текущий запрос:\n"
        f"{context_text}"
        f"Вопрос: {query}\n"
        f"Рассуждение:"
    )

    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": user_content}
    ]