"""
Модуль: src/prompts/templates.py
Назначение: Оптимизированные и компактные шаблоны промптов для измененной вселенной Star Wars.
"""

from typing import List, Dict, Any

# Компактный системный промпт без лишнего «мусора»
SYSTEM_PROMPT = (
    "Ты — ассистент по измененной вселенной Star Wars.\n"
    "Отвечай строго на основе предоставленного контекста.\n\n"
    "ПРАВИЛА И СТРУКТУРА:\n"
    "1. Сначала напиши блок «Рассуждение:» с нумерованными шагами (1, 2, 3), сопоставив факты.\n"
    "2. Затем напиши блок «Ответ:» с итоговым выводом.\n"
    "3. Опирайся ТОЛЬКО на факты из <КОНТЕКСТ>. Не выдумывай факты.\n"
    "4. Если в контексте нет ответа, в блоке «Ответ:» напиши строго: "
    "«Я не знаю. В корпоративной базе знаний нет информации по данному вопросу.»"
)

# Компактные Few-Shot примеры (только каркас формата)
FEW_SHOT_EXAMPLES = (
    "--- ПРИМЕРЫ ---\n"
    "Контекст: mustafar.txt: Чу-Гон Дар создал артефакт — куб Чу-Гон Дара на планете Пирос.\n"
    "Вопрос: Какой объект создал Чу-Гон Дар?\n"
    "Рассуждение:\n"
    "1. В вопросе запрашивается объект, созданный Чу-Гон Даром.\n"
    "2. В mustafar.txt сказано, что он создал «куб Чу-Гон Дара».\n"
    "Ответ: Чу-Гон Дар создал куб Чу-Гон Дара.\n\n"
    "Вопрос: Какая скорость у звездолета Сокол Эфира?\n"
    "Контекст: darth_vader.txt: Ксарн Велгор носил кибернетическую броню.\n"
    "Рассуждение:\n"
    "1. В вопросе запрашивается скорость звездолета «Сокол Эфира».\n"
    "2. В контексте есть данные только о броне Велгора. О звездолете информации нет.\n"
    "Ответ: Я не знаю. В корпоративной базе знаний нет информации по данному вопросу.\n"
    "--- КОНЕЦ ПРИМЕРОВ ---\n\n"
)


def format_rag_messages(query: str, context_chunks: List[Dict[str, Any]]) -> List[Dict[str, str]]:
    """Формирует сжатое тело запроса к LLM."""
    context_text = "<КОНТЕКСТ>\n"
    for i, chunk in enumerate(context_chunks, start=1):
        clean_text = chunk["text"].replace("\n", " ")
        context_text += f"[{i}] {chunk['source_file']}: {clean_text}\n"
    context_text += "</КОНТЕКСТ>\n"

    user_content = (
        f"{FEW_SHOT_EXAMPLES}"
        f"Текущий запрос:\n"
        f"{context_text}"
        f"Вопрос: {query}\n"
        f"Рассуждение:"
    )

    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": user_content}
    ]